"""Adapt an RU-authored scene through monotonic dialogue time mapping.

The editable choreography always runs on the installed RU voice clock. Only
spoken intervals change length; entrances, pauses and exits retain their seconds.
Actual lipsync is generated by Character.facial and is never stretched twice.
"""
import math
from contextlib import contextmanager

from story.cutscenes.content import Character, MotionEvent, CompoundAnim


class RuDialogueTiming:
    def __init__(self, root):
        self.root = root
        self.spans = []
        self.voice_events = {}
        self.durations = {}
        self.fixed_events = {}
        self.fixed_ends = []

    @contextmanager
    def fixed_actions(self, group, minimum_duration=0):
        """Shift a physical action block as a unit; never stretch its animation."""
        anchor = self.root.get_group(group).get_time()
        before = len(self.root.events)
        yield
        for start, event in self.root.events[before:]:
            self.fixed_events[id(event)] = (anchor, start - anchor)
        self.fixed_ends.append((anchor, minimum_duration))

    def keep_fixed_tail(self):
        if self.fixed_ends:
            end = max(self.map_time(anchor) + duration for anchor, duration in self.fixed_ends)
            if end > self.root.get_duration():
                self.root.set_duration(end)

    def duration(self, sound, russian):
        key = (sound.get_nickname(), russian)
        if key not in self.durations:
            value = sound.get_duration(russian)
            if not math.isfinite(value) or value <= 0:
                raise ValueError(f'Invalid voice duration for {key}: {value}')
            self.durations[key] = value
        return self.durations[key]

    def map_time(self, time):
        shift = 0
        for start, reference, actual in self.spans:
            if time <= start:
                return time + shift
            if time < start + reference:
                return start + shift + (time - start) * actual / reference
            shift += actual - reference
        return time + shift

    def build(self, choreography):
        if hasattr(self.root, '_ru_dialogue_timing'):
            raise ValueError('Nested RU dialogue timing is not supported')
        self.root._ru_dialogue_timing = self
        try:
            choreography()
        finally:
            del self.root._ru_dialogue_timing
        # RU is the authored result. Keep exact numbers, animation parameters,
        # event ordering and any manual scene edits, without rounding changes.
        if all(reference == actual for _, reference, actual in self.spans):
            self.keep_fixed_tail()
            return
        mapped = []
        for start, event in self.root.events:
            voice = self.voice_events.get(id(event))
            if voice is not None:
                anchor, offset = voice
                mapped.append((self.map_time(anchor) + offset, event))
                continue
            fixed = self.fixed_events.get(id(event))
            if fixed is not None:
                anchor, offset = fixed
                mapped.append((self.map_time(anchor) + offset, event))
                continue
            mapped_start = self.map_time(start)
            duration = getattr(event, 'duration', None)
            if isinstance(duration, (int, float)) and duration > 0:
                mapped_duration = self.map_time(start + duration) - mapped_start
                event.duration = mapped_duration
                # Keep the same animation progress at the mapped endpoint.
                # Source clip start offsets remain clip-local, not scene times.
                if isinstance(event, (MotionEvent, CompoundAnim)):
                    event.time_scale *= duration / mapped_duration
            for attribute in ('transition_duration', 'trans_time'):
                value = getattr(event, attribute, None)
                if isinstance(value, (int, float)) and value > 0:
                    setattr(event, attribute, self.map_time(start + value) - mapped_start)
            mapped.append((mapped_start, event))
        self.root.events[:] = mapped
        for group in self.root.groups.values():
            group.time = self.map_time(group.time)
        if self.root.duration is not None:
            self.root.duration = self.map_time(self.root.duration)
        self.root.start_time = self.map_time(self.root.start_time)
        self.keep_fixed_tail()


class RuTimedCharacter(Character):
    def facial(self, group, index, append=True, extra_delay=0.3, **kwargs):
        timing = getattr(self.root, '_ru_dialogue_timing', None)
        if timing is None:
            return super().facial(group, index, append=append, extra_delay=extra_delay, **kwargs)
        if not append:
            raise ValueError('RU dialogue timing requires sequential facial(append=True) calls')
        sound = self.root.lookup_single_sound(index)
        reference = timing.duration(sound, True)
        actual = timing.duration(sound, self.root.russian)
        clock = self.root.get_group(group)
        start = clock.get_time()
        if timing.spans and start < timing.spans[-1][0] + timing.spans[-1][1] - 1e-9:
            raise ValueError(f'Overlapping reference dialogue at line {index}')
        before = len(self.root.events)
        super().facial(group, index, append=True, extra_delay=extra_delay, **kwargs)
        for event_time, event in self.root.events[before:]:
            timing.voice_events[id(event)] = (start, event_time - start)
        timing.spans.append((start, reference, actual))
        clock.time = start + (reference + extra_delay)
