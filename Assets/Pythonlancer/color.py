def extract_rgb(hex_color):
    """Извлекает каналы Red, Green, Blue из 24-битного числа."""
    red = (hex_color & 0xFF0000) >> 16
    green = (hex_color & 0x00FF00) >> 8
    blue = (hex_color & 0x0000FF)

    return red, green, blue


def pack_rgb(red, green, blue):
    """Собирает отдельные каналы в одно 24-битное число."""
    return (red << 16) | (green << 8) | blue


